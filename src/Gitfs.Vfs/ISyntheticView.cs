namespace Gitfs.Vfs;

/// <summary>Вьюха, у которой есть файлы без объекта в репозитории и без файла
/// на диске: содержимое собирается в момент открытия.
///
/// Отдельный интерфейс, а не поле в NodeInfo: синтетика есть ровно у одной
/// вьюхи из шести, и класть ссылку на массив в структуру, которая проходит
/// через каждый Lookup и каждую запись листинга, значит платить за неё
/// везде.</summary>
public interface ISyntheticView
{
    /// <summary>Байты файла или null, если путь не синтетический.</summary>
    byte[]? Read(RepoSnapshot snapshot, IReadOnlyList<string> segments);

    /// <summary>Путь на диске для узлов вьюхи, которые всё-таки лежат файлами
    /// (`.gitfs/overlay/…` — то, что записал пользователь). null — узел не
    /// физический. Открывается ТОЛЬКО на чтение: спека §10 обещает видимость
    /// песочницы, а не второй способ в неё писать.</summary>
    string? PhysicalPath(RepoSnapshot snapshot, IReadOnlyList<string> segments);

    /// <summary>Запрещена ли запись по этому ПУТИ.
    ///
    /// Спрашивать про тип вьюхи было нельзя: синтетику отдаёт база всех вьюх
    /// (маркер сабмодуля), и признак «вьюха умеет синтетику» немедленно стал
    /// верным для каждого пути — записи перестали проходить вообще, а поймали
    /// это одиннадцать чужих тестов про песочницу, а не рассуждение.</summary>
    bool IsWriteProtected(IReadOnlyList<string> segments);
}
