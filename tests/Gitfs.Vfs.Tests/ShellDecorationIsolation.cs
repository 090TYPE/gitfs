using System.Runtime.CompilerServices;

namespace Gitfs.Vfs.Tests;

/// <summary>Оформление папок Проводника выключено по умолчанию во всей
/// тестовой сборке.
///
/// Это забота оболочки Windows, а не свойство виртуального дерева. С
/// включённым оформлением каждая проверка листинга несла бы desktop.ini и
/// autorun.inf, и утверждение «корень показывает пять вьюх» превратилось бы
/// в перечисление служебных файлов — смысл проверки размылся бы до
/// неузнаваемости, а сломать её стало бы можно, не сломав ничего настоящего.
///
/// Само оформление закрыто отдельно и на ОБЕИХ настройках:
/// ShellFoldersTests включает его явно и проверяет, что всё на месте, а
/// одна из проверок там убеждается, что при выключенном не отдаётся ничего.</summary>
internal static class ShellDecorationIsolation
{
    [ModuleInitializer]
    internal static void Disable() => ShellFolders.Enabled = false;
}
